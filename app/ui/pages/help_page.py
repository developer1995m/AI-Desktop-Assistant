    def __init__(self, parent: QWidget | None = None) -> None:
        super().__init__(parent)
        self.setObjectName("helpPage")

        layout = QVBoxLayout(self)
        layout.setContentsMargins(32, 24, 32, 24)
        layout.setSpacing(12)

        heading = QLabel("راهنمای کاربر")
        heading.setObjectName("pageTitle")
        layout.addWidget(heading)

        intro = QLabel(
            "در این بخش، کاربرد هر قسمت برنامه، روش استفاده و میانبرهای اصلی را یکجا می‌بینید. "
            "برای موضوع موردنظر، تب مربوطه را انتخاب کنید."
        )
        intro.setObjectName("pageDescription")
        intro.setWordWrap(True)
        layout.addWidget(intro)

        self.tabs = QTabWidget()
        self.tabs.setObjectName("helpTabs")
        self.tabs.setDocumentMode(True)
        self.tabs.setMovable(False)
        self.tabs.setUsesScrollButtons(True)
        self.tabs.setLayoutDirection(Qt.LayoutDirection.RightToLeft)

        for tab_title, key in self.TABS:
            self.tabs.addTab(self._create_tab(self.CONTENT[key]), tab_title)

        layout.addWidget(self.tabs, 1)

    def _create_tab(self, sections: list[tuple[str, list[str]]]) -> QWidget:
        content = QWidget()
        content.setObjectName("helpTabContent")

        body = QVBoxLayout(content)
        body.setContentsMargins(18, 18, 18, 18)
        body.setSpacing(12)

        for title, bullets in sections:
            card = QFrame()
            card.setObjectName("helpCard")
            card_layout = QVBoxLayout(card)
            card_layout.setContentsMargins(16, 14, 16, 14)
            card_layout.setSpacing(8)

            title_label = QLabel(title)
            title_label.setObjectName("panelHeading")
            card_layout.addWidget(title_label)

            for item in bullets:
                label = QLabel(f"• {item}")
                label.setObjectName("helpText")
                label.setWordWrap(True)
                label.setTextInteractionFlags(Qt.TextInteractionFlag.TextSelectableByMouse)
                card_layout.addWidget(label)

            body.addWidget(card)

        body.addStretch(1)

        scroll = QScrollArea()
        scroll.setObjectName("helpScroll")
        scroll.setWidgetResizable(True)
        scroll.setFrameShape(QFrame.Shape.NoFrame)
        scroll.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
        scroll.setStyleSheet(
            "QScrollArea { background: transparent; border: none; }"
            "QScrollArea > QWidget > QWidget { background: transparent; }"
        )
        scroll.viewport().setAutoFillBackground(False)
        scroll.setWidget(content)
        return scroll
